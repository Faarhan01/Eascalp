import { useMemo, useRef, useState } from 'react';
import { Trash2, Upload } from 'lucide-react';
import type { UploadedCsvDataset } from '../types/project';
import { computeCsvMetrics, parseMt5CsvFiles } from '../utils/csvParser';

function SvgLineChart({
  title,
  values,
  strokeColor,
  formatVal,
}: {
  title: string;
  values: number[];
  strokeColor: string;
  formatVal: (v: number) => string;
}) {
  if (values.length < 2) {
    return (
      <div className="rounded-lg border border-slate-800 bg-slate-900/60 p-4">
        <p className="text-xs font-medium text-slate-300">{title}</p>
        <p className="mt-8 text-center text-xs text-slate-500">
          Need at least 2 closed trades in trade_history.csv to plot curve.
        </p>
      </div>
    );
  }

  const w = 520;
  const h = 180;
  const pad = 16;
  const min = Math.min(...values);
  const max = Math.max(...values);
  const span = Math.max(1e-6, max - min);

  const pts = values
    .map((v, i) => {
      const x = pad + (i / (values.length - 1)) * (w - pad * 2);
      const y = h - pad - ((v - min) / span) * (h - pad * 2);
      return `${x.toFixed(1)},${y.toFixed(1)}`;
    })
    .join(' ');

  return (
    <div className="rounded-lg border border-slate-800 bg-slate-900/60 p-4">
      <div className="flex items-center justify-between text-xs">
        <span className="font-medium text-slate-200">{title}</span>
        <span className="font-mono text-slate-400 tabular-nums">
          Min {formatVal(min)} · Max {formatVal(max)}
        </span>
      </div>
      <svg viewBox={`0 0 ${w} ${h}`} className="mt-3 h-44 w-full overflow-visible">
        <line x1={pad} y1={h / 2} x2={w - pad} y2={h / 2} stroke="#1E293B" strokeDasharray="3 3" />
        <polyline fill="none" stroke={strokeColor} strokeWidth="2" points={pts} />
      </svg>
    </div>
  );
}

export default function PerformanceTerminalView() {
  const inputRef = useRef<HTMLInputElement | null>(null);
  const [dataset, setDataset] = useState<UploadedCsvDataset | null>(null);
  const [parsing, setParsing] = useState(false);
  const [strategyFilter, setStrategyFilter] = useState('ALL');
  const [activeSubTab, setActiveSubTab] = useState<'trades' | 'rejections' | 'signals'>('trades');

  const metrics = useMemo(() => (dataset ? computeCsvMetrics(dataset) : null), [dataset]);

  const strategiesInTrades = useMemo(() => {
    if (!dataset) return ['ALL'];
    const s = new Set<string>();
    for (const t of dataset.trades) s.add(t.strategy);
    return ['ALL', ...Array.from(s)];
  }, [dataset]);

  const filteredTrades = useMemo(() => {
    if (!dataset) return [];
    if (strategyFilter === 'ALL') return dataset.trades;
    return dataset.trades.filter((t) => t.strategy === strategyFilter);
  }, [dataset, strategyFilter]);

  async function handleFiles(fileList: FileList | null) {
    if (!fileList || fileList.length === 0) return;
    setParsing(true);
    try {
      const parsed = await parseMt5CsvFiles(fileList);
      setDataset(parsed);
    } finally {
      setParsing(false);
    }
  }

  return (
    <div className="space-y-6">
      <div className="flex flex-col gap-3 border-b border-slate-800 pb-4 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <h1 className="font-display text-xl font-semibold text-slate-100">
            Read-Only MT5 CSV Performance Terminal
          </h1>
          <p className="mt-1 text-xs text-slate-400">
            Upload real CSV exports generated by <span className="font-mono text-slate-300">CSVLogger.mqh</span> in{' '}
            <span className="font-mono text-slate-300">MQL5/Files/AdvancedScalpingEA/Exports/</span>. Zero simulated or fabricated data is displayed.
          </p>
        </div>

        <div className="flex items-center gap-2 shrink-0">
          <input
            ref={inputRef}
            type="file"
            multiple
            accept=".csv,text/csv"
            className="hidden"
            onChange={(e) => handleFiles(e.target.files)}
          />
          <button
            type="button"
            onClick={() => inputRef.current?.click()}
            disabled={parsing}
            className="inline-flex items-center gap-2 rounded-lg bg-sky-600 px-4 py-2 text-xs font-medium text-white hover:bg-sky-500 disabled:opacity-50 whitespace-nowrap shrink-0"
          >
            <Upload className="h-3.5 w-3.5" />
            <span>{parsing ? 'Parsing CSVs...' : 'Upload MT5 CSV Files'}</span>
          </button>
          {dataset && (
            <button
              type="button"
              onClick={() => setDataset(null)}
              className="inline-flex items-center gap-1.5 rounded-lg border border-slate-700 bg-slate-900 px-3 py-2 text-xs font-medium text-slate-300 hover:bg-slate-800 whitespace-nowrap shrink-0"
            >
              <Trash2 className="h-3.5 w-3.5" />
              <span>Clear</span>
            </button>
          )}
        </div>
      </div>

      {!dataset || !metrics ? (
        <div className="rounded-lg border border-dashed border-slate-700 bg-slate-900/40 p-10 text-center">
          <p className="font-display text-base font-medium text-slate-200">
            No MT5 CSV Export Data Loaded
          </p>
          <p className="mx-auto mt-2 max-w-xl text-xs leading-relaxed text-slate-400">
            To preserve strict analytical honesty, this terminal never generates synthetic backtest curves or fake win rates.
            Run <span className="font-mono text-slate-300">AdvancedScalpingEA</span> in MetaTrader 5 Strategy Tester or Demo mode,
            then select one or more exported CSV files (<span className="font-mono text-slate-300">trade_history.csv</span>,{' '}
            <span className="font-mono text-slate-300">strategy_signals.csv</span>,{' '}
            <span className="font-mono text-slate-300">rejected_signals.csv</span>,{' '}
            <span className="font-mono text-slate-300">risk_events.csv</span>) to inspect actual performance.
          </p>
          <button
            type="button"
            onClick={() => inputRef.current?.click()}
            className="mt-5 inline-flex items-center gap-2 rounded-lg border border-slate-700 bg-slate-900 px-4 py-2 text-xs font-medium text-slate-200 hover:border-slate-600 hover:bg-slate-800"
          >
            <Upload className="h-3.5 w-3.5" />
            <span>Select CSV Files from Computer</span>
          </button>
        </div>
      ) : (
        <div className="space-y-6">
          <div className="text-xs text-slate-400">
            Loaded files: <span className="font-mono text-slate-200">{dataset.loadedFiles.join(' · ')}</span>
          </div>

          {/* KPI Strip */}
          <div className="grid grid-cols-2 gap-4 sm:grid-cols-3 lg:grid-cols-6">
            <div className="rounded-lg border border-slate-800 bg-slate-900/70 p-3.5">
              <p className="text-xs text-slate-400">Closed Trades</p>
              <p className="mt-1 font-mono text-xl font-semibold text-slate-100 tabular-nums">
                {metrics.closedTrades}
              </p>
            </div>
            <div className="rounded-lg border border-slate-800 bg-slate-900/70 p-3.5">
              <p className="text-xs text-slate-400">Realized Net PnL</p>
              <p
                className={`mt-1 font-mono text-xl font-semibold tabular-nums ${
                  metrics.netProfit >= 0 ? 'text-emerald-400' : 'text-red-400'
                }`}
              >
                {metrics.netProfit >= 0 ? '+' : ''}
                {metrics.netProfit.toFixed(2)}
              </p>
            </div>
            <div className="rounded-lg border border-slate-800 bg-slate-900/70 p-3.5">
              <p className="text-xs text-slate-400">Win Rate</p>
              <p className="mt-1 font-mono text-xl font-semibold text-slate-100 tabular-nums">
                {metrics.winRatePct.toFixed(1)}%
              </p>
            </div>
            <div className="rounded-lg border border-slate-800 bg-slate-900/70 p-3.5">
              <p className="text-xs text-slate-400">Profit Factor</p>
              <p className="mt-1 font-mono text-xl font-semibold text-slate-100 tabular-nums">
                {metrics.profitFactor.toFixed(2)}
              </p>
            </div>
            <div className="rounded-lg border border-slate-800 bg-slate-900/70 p-3.5">
              <p className="text-xs text-slate-400">Max Drawdown</p>
              <p className="mt-1 font-mono text-xl font-semibold text-amber-400 tabular-nums">
                -{metrics.maxDrawdownMoney.toFixed(2)}
              </p>
            </div>
            <div className="rounded-lg border border-slate-800 bg-slate-900/70 p-3.5">
              <p className="text-xs text-slate-400">Rejected Signals</p>
              <p className="mt-1 font-mono text-xl font-semibold text-slate-100 tabular-nums">
                {dataset.rejectedSignals.length}
              </p>
            </div>
          </div>

          {/* Equity & Drawdown Curves */}
          <div className="grid gap-4 lg:grid-cols-2">
            <SvgLineChart
              title="Cumulative Realized PnL Curve"
              values={metrics.equitySeries}
              strokeColor="#38BDF8"
              formatVal={(v) => v.toFixed(2)}
            />
            <SvgLineChart
              title="Realized Drawdown Curve"
              values={metrics.drawdownSeries}
              strokeColor="#DC2626"
              formatVal={(v) => v.toFixed(2)}
            />
          </div>

          {/* Strategy Breakdown & Rejection Reasons */}
          {metrics.strategyBreakdown.length > 0 && (
            <div className="rounded-lg border border-slate-800 bg-slate-900/60 overflow-hidden">
              <div className="border-b border-slate-800 px-5 py-3">
                <h2 className="font-display text-sm font-semibold text-slate-100">
                  Strategy Performance Attribution (Actual CSV Trades)
                </h2>
              </div>
              <div className="overflow-x-auto">
                <table className="w-full text-left text-xs">
                  <thead className="border-b border-slate-800 bg-slate-950/60 text-slate-400">
                    <tr>
                      <th className="px-4 py-2.5 font-medium">Strategy</th>
                      <th className="px-4 py-2.5 font-medium text-right">Trades</th>
                      <th className="px-4 py-2.5 font-medium text-right">Wins</th>
                      <th className="px-4 py-2.5 font-medium text-right">Win Rate</th>
                      <th className="px-4 py-2.5 font-medium text-right">Profit Factor</th>
                      <th className="px-4 py-2.5 font-medium text-right">Net Profit</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-800/70 font-mono tabular-nums">
                    {metrics.strategyBreakdown.map((s) => (
                      <tr key={s.strategy} className="hover:bg-slate-800/30">
                        <td className="px-4 py-2.5 font-sans font-medium text-slate-200">{s.strategy}</td>
                        <td className="px-4 py-2.5 text-right text-slate-300">{s.trades}</td>
                        <td className="px-4 py-2.5 text-right text-slate-300">{s.wins}</td>
                        <td className="px-4 py-2.5 text-right text-slate-300">{s.winRatePct.toFixed(1)}%</td>
                        <td className="px-4 py-2.5 text-right text-slate-300">{s.profitFactor.toFixed(2)}</td>
                        <td
                          className={`px-4 py-2.5 text-right ${
                            s.netProfit >= 0 ? 'text-emerald-400' : 'text-red-400'
                          }`}
                        >
                          {s.netProfit >= 0 ? '+' : ''}
                          {s.netProfit.toFixed(2)}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </div>
          )}

          {/* Tabbed Audit Ledger */}
          <div className="rounded-lg border border-slate-800 bg-slate-900/60 overflow-hidden">
            <div className="flex flex-wrap items-center justify-between gap-3 border-b border-slate-800 px-4 py-3">
              <div className="flex items-center gap-1 rounded-lg bg-slate-950 p-1">
                <button
                  type="button"
                  onClick={() => setActiveSubTab('trades')}
                  className={`rounded-md px-3 py-1.5 text-xs font-medium transition-colors whitespace-nowrap ${
                    activeSubTab === 'trades' ? 'bg-slate-800 text-slate-100' : 'text-slate-400 hover:text-slate-200'
                  }`}
                >
                  Trade Ledger ({dataset.trades.length})
                </button>
                <button
                  type="button"
                  onClick={() => setActiveSubTab('signals')}
                  className={`rounded-md px-3 py-1.5 text-xs font-medium transition-colors whitespace-nowrap ${
                    activeSubTab === 'signals' ? 'bg-slate-800 text-slate-100' : 'text-slate-400 hover:text-slate-200'
                  }`}
                >
                  Accepted Signals ({dataset.signals.length})
                </button>
                <button
                  type="button"
                  onClick={() => setActiveSubTab('rejections')}
                  className={`rounded-md px-3 py-1.5 text-xs font-medium transition-colors whitespace-nowrap ${
                    activeSubTab === 'rejections' ? 'bg-slate-800 text-slate-100' : 'text-slate-400 hover:text-slate-200'
                  }`}
                >
                  Rejected Signals ({dataset.rejectedSignals.length})
                </button>
              </div>

              {activeSubTab === 'trades' && (
                <select
                  value={strategyFilter}
                  onChange={(e) => setStrategyFilter(e.target.value)}
                  className="rounded-md border border-slate-800 bg-slate-950 px-2.5 py-1.5 text-xs text-slate-200"
                >
                  {strategiesInTrades.map((s) => (
                    <option key={s} value={s}>
                      {s === 'ALL' ? 'All Strategies' : s}
                    </option>
                  ))}
                </select>
              )}
            </div>

            <div className="max-h-[400px] overflow-auto">
              {activeSubTab === 'trades' && (
                <table className="w-full text-left text-xs">
                  <thead className="sticky top-0 border-b border-slate-800 bg-slate-950 text-slate-400">
                    <tr>
                      <th className="px-4 py-2.5 font-medium">Timestamp</th>
                      <th className="px-4 py-2.5 font-medium">Symbol</th>
                      <th className="px-4 py-2.5 font-medium">Strategy</th>
                      <th className="px-4 py-2.5 font-medium">Status</th>
                      <th className="px-4 py-2.5 font-medium text-right">Score</th>
                      <th className="px-4 py-2.5 font-medium text-right">Net PnL</th>
                      <th className="px-4 py-2.5 font-medium">Split</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-800/60 font-mono tabular-nums">
                    {filteredTrades.length === 0 ? (
                      <tr>
                        <td colSpan={7} className="px-4 py-8 text-center font-sans text-slate-500">
                          No trade_history.csv rows found.
                        </td>
                      </tr>
                    ) : (
                      filteredTrades.slice(0, 200).map((t, idx) => (
                        <tr key={idx} className="hover:bg-slate-800/30">
                          <td className="px-4 py-2 text-slate-400 whitespace-nowrap">{t.timestamp}</td>
                          <td className="px-4 py-2 text-slate-200">{t.symbol}</td>
                          <td className="px-4 py-2 font-sans text-slate-300">{t.strategy}</td>
                          <td className="px-4 py-2 text-slate-300">{t.status}</td>
                          <td className="px-4 py-2 text-right text-slate-300">{t.score.toFixed(1)}</td>
                          <td
                            className={`px-4 py-2 text-right ${
                              t.netPnL > 0 ? 'text-emerald-400' : t.netPnL < 0 ? 'text-red-400' : 'text-slate-400'
                            }`}
                          >
                            {t.netPnL.toFixed(2)}
                          </td>
                          <td className="px-4 py-2 text-slate-400">{t.splitTag}</td>
                        </tr>
                      ))
                    )}
                  </tbody>
                </table>
              )}

              {activeSubTab === 'signals' && (
                <table className="w-full text-left text-xs">
                  <thead className="sticky top-0 border-b border-slate-800 bg-slate-950 text-slate-400">
                    <tr>
                      <th className="px-4 py-2.5 font-medium">Timestamp</th>
                      <th className="px-4 py-2.5 font-medium">Strategy</th>
                      <th className="px-4 py-2.5 font-medium">Dir</th>
                      <th className="px-4 py-2.5 font-medium text-right">Score</th>
                      <th className="px-4 py-2.5 font-medium">Regime</th>
                      <th className="px-4 py-2.5 font-medium">Recorded Rationale</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-800/60">
                    {dataset.signals.length === 0 ? (
                      <tr>
                        <td colSpan={6} className="px-4 py-8 text-center text-slate-500">
                          No strategy_signals.csv rows found.
                        </td>
                      </tr>
                    ) : (
                      dataset.signals.slice(0, 200).map((s, idx) => (
                        <tr key={idx} className="hover:bg-slate-800/30">
                          <td className="px-4 py-2 font-mono text-slate-400 whitespace-nowrap">{s.timestamp}</td>
                          <td className="px-4 py-2 text-slate-200">{s.strategy}</td>
                          <td className="px-4 py-2 font-mono text-sky-400">{s.direction}</td>
                          <td className="px-4 py-2 font-mono text-right text-slate-200 tabular-nums">{s.score.toFixed(1)}</td>
                          <td className="px-4 py-2 text-slate-300">{s.regime}</td>
                          <td className="px-4 py-2 text-slate-400">{s.rationale}</td>
                        </tr>
                      ))
                    )}
                  </tbody>
                </table>
              )}

              {activeSubTab === 'rejections' && (
                <table className="w-full text-left text-xs">
                  <thead className="sticky top-0 border-b border-slate-800 bg-slate-950 text-slate-400">
                    <tr>
                      <th className="px-4 py-2.5 font-medium">Timestamp</th>
                      <th className="px-4 py-2.5 font-medium">Strategy</th>
                      <th className="px-4 py-2.5 font-medium">Code</th>
                      <th className="px-4 py-2.5 font-medium text-right">Score</th>
                      <th className="px-4 py-2.5 font-medium">Rejection Reason</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-800/60">
                    {dataset.rejectedSignals.length === 0 ? (
                      <tr>
                        <td colSpan={5} className="px-4 py-8 text-center text-slate-500">
                          No rejected_signals.csv rows found.
                        </td>
                      </tr>
                    ) : (
                      dataset.rejectedSignals.slice(0, 200).map((r, idx) => (
                        <tr key={idx} className="hover:bg-slate-800/30">
                          <td className="px-4 py-2 font-mono text-slate-400 whitespace-nowrap">{r.timestamp}</td>
                          <td className="px-4 py-2 text-slate-200">{r.strategy}</td>
                          <td className="px-4 py-2 font-mono text-amber-400">{r.rejectionCode}</td>
                          <td className="px-4 py-2 font-mono text-right text-slate-300 tabular-nums">{r.score.toFixed(1)}</td>
                          <td className="px-4 py-2 text-slate-400">{r.rejectionReason}</td>
                        </tr>
                      ))
                    )}
                  </tbody>
                </table>
              )}
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
